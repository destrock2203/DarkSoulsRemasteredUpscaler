"""Generates src/game/shader_table.inc and src/game/shader_ids.h from the game's shader archives.

Dark Souls Remastered loads its shaders from <game>/shader/*_DX11.shaderbnd.dcx (zlib-compressed BND3
containers of DXBC files named after the shader, e.g. FRPG_Fil_ResolveTAA.fpo). The game passes each
file's bytes unchanged to ID3D11Device::Create*Shader, so a shader is identified at runtime by the
first 8 bytes of its DXBC checksum (bytes 4..11), and named from this table.

Usage: python tools/gen_shader_table.py "<DARK SOULS REMASTERED folder>"
"""
import glob
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "src", "game")

# Pixel / vertex / compute shaders the mod refers to by name (unique ids checked below).
KEY_SHADERS = {
    "kPsResolveTaa": "FRPG_Fil_ResolveTAA.fpo",
    "kPsFxaa": "FRPG_Fil_FxAA2.fpo",
    "kPsHdr": "FRPG_Fil_HDR.fpo",
    "kPsHdrColAdj": "FRPG_Fil_HDR_ColAdj.fpo",
    "kPsHdrPbl": "FRPG_Fil_HDR_PBL.fpo",
    "kPsHdrPblColAdj": "FRPG_Fil_HDR_PBL_ColAdj.fpo",
    "kPsHdrMenu": "FRPG_Fil_HDR_Menu.fpo",
    "kPsMotionBlurPre": "FRPG_Fil_MotionBlurPre.fpo",
    "kPsMotionBlurFinal": "FRPG_Fil_MotionBlurFinal.fpo",
    "kPsDepthCopy": "FRPG_Fil_DepthCopy.fpo",
    "kPsBloom": "FRPG_Fil_Bloom.fpo",
    "kPsDof": "FRPG_Fil_Dof.fpo",
    "kPsBlackBars": "FRPG_Fil_BlackBars.fpo",
    "kPsMenuCol": "FRPG_Menu_Col.fpo",
    "kPsMenuColTex": "FRPG_Menu_ColTex.fpo",
    "kPsMenuFontSharpen": "FRPG_Menu_FontSharpen.fpo",
    "kVsMenuCommon": "FRPG_Menu_Common.vpo",
    "kVsMenuFont": "FRPG_Menu_Font.vpo",
    "kVsMenuFontAl": "FRPG_Menu_Font_AL.vpo",
    "kVsFilterQuad": "FRPG_Fil_ResolveTAA.vpo",
}

CATEGORIES = {
    "FRPG_Filter_DX11": "kFilter",
    "FRPG_Menu_DX11": "kMenu",
    "FRPG_Deferred_DX11": "kDeferred",
    "FRPG_SfxPBL_DX11": "kSfx",
    "FRPG_FlverPBL_fpo_DX11": "kModel",
    "FRPG_FlverPBL_vpo_DX11": "kModel",
    "DbgFont_DX11": "kDebug",
}


def undcx(data):
    if data[:4] != b"DCX\0":
        raise ValueError("not a DCX file")
    return zlib.decompress(data[0x4C:])


def bnd3_entries(data):
    if data[:4] != b"BND3":
        raise ValueError("not a BND3 container")
    fmt = data[0xC]
    count = struct.unpack_from("<I", data, 0x10)[0]
    entry_size = 0x18 if (fmt & 0x04) else 0x14
    offset = 0x20
    for _ in range(count):
        _flags, size, data_offset, _id, name_offset = struct.unpack_from("<IIIII", data, offset)
        name = data[name_offset:data.index(b"\0", name_offset)].decode("shift_jis", "replace")
        yield name.replace("\\", "/").split("/")[-1], data[data_offset:data_offset + size]
        offset += entry_size


def flags_for(name):
    base = name.rsplit(".", 1)[0]
    suffix = base.rsplit("_", 1)[-1]
    flags = []
    if suffix in ("Vel", "VelAlp"):
        flags.append("kVelocity")
    if suffix in ("Dep", "DepAlp"):
        flags.append("kDepthOnly")
    if suffix in ("Sdw", "sdw"):
        flags.append("kShadow")
    return flags


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    shader_dir = os.path.join(sys.argv[1], "shader")
    table = {}  # id -> [stage, categories(set), names(list)]
    for path in sorted(glob.glob(os.path.join(shader_dir, "*_DX11.shaderbnd.dcx"))):
        archive = os.path.basename(path).split(".")[0]
        category = CATEGORIES.get(archive, "kOther")
        for name, blob in bnd3_entries(undcx(open(path, "rb").read())):
            if blob[:4] != b"DXBC":
                continue
            shader_id = struct.unpack_from("<Q", blob, 4)[0]
            stage = {"vpo": "kVertex", "fpo": "kPixel", "cpo": "kCompute"}.get(name.rsplit(".", 1)[-1], "kOther")
            entry = table.setdefault(shader_id, [stage, set(), []])
            entry[1].add(category)
            entry[1].update(flags_for(name))
            entry[2].append(name)

    ids = {}
    for const, name in KEY_SHADERS.items():
        matches = [k for k, v in table.items() if name in v[2]]
        if len(matches) != 1:
            raise SystemExit(f"{name}: {len(matches)} matches")
        ids[const] = (matches[0], table[matches[0]][2])

    with open(os.path.join(OUT_DIR, "shader_table.inc"), "w", newline="\n") as out:
        out.write("// Generated by tools/gen_shader_table.py from the game's shader archives. Do not edit.\n")
        out.write("// {id (DXBC checksum bytes 4..11), stage, flags, names (identical bytecode shares one id)}\n")
        for shader_id in sorted(table):
            stage, cats, names = table[shader_id]
            flags = " | ".join(sorted(cats))
            joined = "|".join(n.rsplit(".", 1)[0] for n in names)
            out.write(f'{{0x{shader_id:016x}ull, Stage::{stage}, {flags}, "{joined}"}},\n')

    with open(os.path.join(OUT_DIR, "shader_ids.h"), "w", newline="\n") as out:
        out.write("#pragma once\n\n")
        out.write("// Generated by tools/gen_shader_table.py from the game's shader archives. Do not edit.\n")
        out.write("// Ids (DXBC checksum bytes 4..11) of the shaders the mod refers to by name.\n\n")
        out.write("#include <cstdint>\n\nnamespace dsru::game::shader_id {\n\n")
        for const, (shader_id, names) in ids.items():
            out.write(f"inline constexpr uint64_t {const} = 0x{shader_id:016x}ull;  // {', '.join(names)}\n")
        out.write("\n}  // namespace dsru::game::shader_id\n")

    print(f"{sum(len(v[2]) for v in table.values())} shaders, {len(table)} ids -> {os.path.normpath(OUT_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
